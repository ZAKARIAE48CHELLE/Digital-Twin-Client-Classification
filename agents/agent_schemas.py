"""
OSMOS Multi-Agent Supervision Layer — Data Schemas (Phase 8.1)
================================================================
Defines dataclasses and typed dictionaries for Agent Context, Agent Outputs,
Evidence Traceability, and Orchestrator Supervision Reports.
"""

from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional


@dataclass
class EvidenceItem:
    """Evidence traceability schema mapping metric, observed value, threshold, and interpretation."""
    metric_name: str
    value: Any
    threshold: Any
    interpretation: str

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class AgentContext:
    """Structured context dictionary built for a single entity in read-only mode."""
    entity_id: str
    entity_type: str = "Client"  # "Client" or "Prospect"
    latest_digital_twin: Dict[str, Any] = field(default_factory=dict)
    latest_rfm: Dict[str, Any] = field(default_factory=dict)
    latest_clv: Dict[str, Any] = field(default_factory=dict)
    latest_classification: Dict[str, Any] = field(default_factory=dict)
    latest_segment: str = "Unknown"
    latest_persona: str = "Unknown"
    recent_events: List[Dict[str, Any]] = field(default_factory=list)
    campaign_history: List[Dict[str, Any]] = field(default_factory=list)
    journey_history: List[Dict[str, Any]] = field(default_factory=list)
    dynamic_persona_context: Dict[str, Any] = field(default_factory=dict)
    knowledge_results: List[Dict[str, Any]] = field(default_factory=list)
    decision_memory: List[Dict[str, Any]] = field(default_factory=list)
    documentation_context: List[Dict[str, Any]] = field(default_factory=list)
    previous_agent_runs: List[Dict[str, Any]] = field(default_factory=list)
    approval_history: List[Dict[str, Any]] = field(default_factory=list)
    storage_mode: str = "excel"  # "postgres" or "excel"
    timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class AgentOutput:
    """Structured output returned by each specialized agent."""
    agent_id: str
    agent_name: str
    agent_role: str
    status: str  # "OK", "Warning", "Critical", "Insufficient Data", "Error"
    summary: str
    observations: List[str] = field(default_factory=list)
    risks: List[str] = field(default_factory=list)
    opportunities: List[str] = field(default_factory=list)
    recommendations: List[str] = field(default_factory=list)
    confidence_score: float = 1.0
    evidence: List[Dict[str, Any]] = field(default_factory=list)
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class OrchestratorOutput:
    """Consolidated supervision report generated by the Multi-Agent Orchestrator."""
    entity_id: str
    global_status: str  # "OK", "Warning", "Critical", "Insufficient Data", "Error"
    final_summary: str
    agent_outputs: List[Dict[str, Any]] = field(default_factory=list)
    consolidated_risks: List[str] = field(default_factory=list)
    consolidated_opportunities: List[str] = field(default_factory=list)
    final_recommendations: List[str] = field(default_factory=list)
    recommended_next_best_action: str = "No immediate action required"
    confidence_score: float = 1.0
    llm_executive_summary: Optional[Dict[str, Any]] = None
    debate_output: Optional[Dict[str, Any]] = None
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)
